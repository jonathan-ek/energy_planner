def find_nearest_quater_hour(timestamp):
    minute = (timestamp.minute // 15) * 15
    return timestamp.replace(minute=minute, second=0, microsecond=0)


async def format_forecasts(name, forecast_solar, forecast_quartz):
    print(name)
    estimates = {}
    for str_timestamp, forecast in (
        forecast_quartz.get("predictions", {}).get("power_kw", {}).items()
    ):
        timestamp = find_nearest_quater_hour(
            datetime.datetime.strptime(str_timestamp, "%Y-%m-%dT%H:%M:%S.%f").replace(
                tzinfo=datetime.timezone.utc
            )
        )
        estimates[timestamp.isoformat()] = int(forecast * 1000)  # convert kW to W
    print("Quartz estimates (W):", estimates)
    solar_estimates = {}
    solar_estimate_list = []
    for str_timestamp, forecast in (
        forecast_solar.get("result", {}).get("watts", {}).items()
    ):
        timestamp = find_nearest_quater_hour(
            datetime.datetime.strptime(str_timestamp, "%Y-%m-%d %H:%M:%S").replace(
                tzinfo=ZoneInfo("Europe/Stockholm")
            )
        ).astimezone(datetime.timezone.utc)
        solar_estimate_list.append((timestamp, forecast))
    for i, (timestamp, forecast) in enumerate(solar_estimate_list):
        solar_estimates[timestamp.isoformat()] = forecast
        if i + 1 < len(solar_estimate_list):
            next_timestamp = timestamp + datetime.timedelta(minutes=15)
            while next_timestamp < solar_estimate_list[i + 1][0]:
                # linear interpolation
                solar_estimates[next_timestamp.isoformat()] = int(
                    forecast
                    + (solar_estimate_list[i + 1][1] - forecast)
                    * (
                        (next_timestamp - timestamp).total_seconds()
                        / (solar_estimate_list[i + 1][0] - timestamp).total_seconds()
                    )
                )
                next_timestamp = next_timestamp + datetime.timedelta(minutes=15)
    print("Forecast.solar estimates (W):", solar_estimates)
    combined_estimates = {}
    now = datetime.datetime.now(tz=datetime.timezone.utc)
    for i in range(0, 48 * 4):
        timestamp = find_nearest_quater_hour(now + datetime.timedelta(minutes=i * 15))
        solar_value = solar_estimates.get(timestamp.isoformat())
        quartz_value = estimates.get(timestamp.isoformat())
        if solar_value is not None and quartz_value is not None:
            combined_estimates[timestamp.isoformat()] = int(
                (solar_value + quartz_value) / 2
            )
        elif solar_value is not None:
            combined_estimates[timestamp.isoformat()] = solar_value
        elif quartz_value is not None:
            combined_estimates[timestamp.isoformat()] = quartz_value
        else:
            combined_estimates[timestamp.isoformat()] = 0
    print("Combined estimates (W):", combined_estimates)
    return combined_estimates


def join_estimates(est1, est2):
    combined = {}
    for key in set(est1.keys()).union(set(est2.keys())):
        val1 = est1.get(key)
        val2 = est2.get(key)
        if val1 is not None and val2 is not None:
            combined[key] = val1 + val2
        elif val1 is not None:
            combined[key] = val1
        elif val2 is not None:
            combined[key] = val2
        else:
            combined[key] = 0
    return combined


