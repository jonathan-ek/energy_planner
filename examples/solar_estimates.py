async def fetch_forecast_solar(client, lat, lon, dec, az, kwp):
    url = f"https://api.forecast.solar/estimate/{lat}/{lon}/{dec}/{az - 180}/{kwp}"
    async with client.get(url) as response:
        response.raise_for_status()
        return await response.json()


async def fetch_forecast_quartz(client: aiohttp.ClientSession, lat, lon, dec, az, kwp):
    url = "https://open.quartz.solar/forecast/"
    async with client.post(
        url,
        json={
            "site": {
                "latitude": str(lat),
                "longitude": str(lon),
                "capacity_kwp": str(kwp),
                "tilt": str(dec),
                "orientation": str(az),
            }
        },
        headers={"Content-Type": "application/json"},
    ) as response:
        response.raise_for_status()
        return await response.json()


